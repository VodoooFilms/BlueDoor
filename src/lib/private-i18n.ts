// Localize interface copy and backend notices, never document contents.
export function privateCopy(text: string): string {
  if (getLang() !== "en") return text;
  if (ENGLISH[text]) return ENGLISH[text];
  let result = text
    .replace(/Posible (\w+) residual: corrige el mapa antes de aprobar\./g, "Potential residual $1: correct the map before exporting.")
    .replace(/Una entidad (\w+) del mapa sigue presente en la salida\./g, "A $1 entity from the map is still present in the output.");
  for (const source of Object.keys(ENGLISH).sort((a, b) => b.length - a.length)) {
    result = result.split(source).join(ENGLISH[source]);
  }
  return result
    .replace(/Posible (\w+) residual: corrige el mapa antes de aprobar\./g, "Potential residual $1: correct the map before exporting.")
    .replace(/Una entidad (\w+) del mapa sigue presente en la salida\./g, "A $1 entity from the map is still present in the output.");
}
